def seed_demand_events(env):
    """Create the shipped calendar once; never touch what a user has edited."""
    Event = env['al.demand.event']
    for event_type, calendar, name, start, end, lead, confirmed, closed in SEED:
        if Event.search_count([('name', '=', name)]):
            continue
        Event.create({
            'name': name,
            'event_type': event_type,
            'calendar': calendar,
            'date_start': start,
            'date_end': end,
            'lead_days': lead,
            'confirmed': confirmed,
            'closed': closed,
        })


def post_init_hook(env):
    seed_demand_events(env)
