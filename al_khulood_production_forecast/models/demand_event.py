# -*- coding: utf-8 -*-
"""Occasions that move demand, anchored to either calendar.

Both calendars are first-class here. An event is either:

* ``hijri``     - Ramadan, the two Eids, Ashura. These move ~11 days earlier
                  every Gregorian year, so each occurrence is its own record
                  with its own real (moon-sighted) dates.
* ``gregorian`` - National Day, New Year, Valentine's, Mother's Day. Fixed
                  dates, but they still need a record per year so the forecast
                  can learn how much each one actually lifted sales.

The dates stored here are what the forecast learns from and applies. The
arithmetic Hijri conversion in tools/hijri.py never overrides them, because
Bahrain starts a month on a sighting, not on a calculation.
"""
import math
from datetime import timedelta
from statistics import median

from odoo import _, api, fields, models
from odoo.exceptions import UserError

# How far either side of a computed date to look for the real one. The tabular
# calendar was never more than one day out across 29 observed occasions, so
# three days is generous without straying into the next occasion.
SEARCH_RADIUS = 3


class DemandEvent(models.Model):
    _name = 'al.demand.event'
    _description = 'Demand Event (Hijri or Gregorian)'
    _order = 'date_start desc, id desc'

    name = fields.Char(required=True)
    event_type = fields.Selection([
        ('ramadan', 'Ramadan'),
        ('eid_fitr', 'Eid al-Fitr'),
        ('eid_adha', 'Eid al-Adha'),
        ('muharram', 'Muharram (mourning period)'),
        ('ashura', 'Ashura'),
        ('hijri_new_year', 'Hijri New Year'),
        ('national_day', 'Bahrain National Day'),
        ('new_year', 'New Year'),
        ('valentine', "Valentine's Day"),
        ('mother_day', "Mother's Day"),
        ('other', 'Other'),
    ], required=True, index=True)
    calendar = fields.Selection([
        ('hijri', 'Islamic (Hijri)'),
        ('gregorian', 'Gregorian'),
    ], required=True, default='hijri', index=True,
        help="Which calendar this occasion is anchored to.")
    date_start = fields.Date(required=True, index=True)
    date_end = fields.Date(required=True, index=True)
    lead_days = fields.Integer(
        default=0,
        help="Days before the start that already carry the rush "
             "(gift boxes are bought before the date, not on it).")
    confirmed = fields.Boolean(
        default=False,
        help="Set once the real date is known - for Hijri events, after the "
             "moon sighting is announced. Unconfirmed dates are estimates.")
    closed = fields.Boolean(
        string='Branches closed',
        help="The shops do not trade on this day. Four years of sales show "
             "exactly zero tickets on Ashura, so nothing is forecast and "
             "nothing is produced for it.")
    active = fields.Boolean(default=True)
    rule_id = fields.Many2one(
        'al.demand.event.rule', string='Generated by', ondelete='set null',
        index=True,
        help="The recurrence rule this occasion came from. Empty means it was "
             "entered by hand, which always outranks a generated date.")
    source_year = fields.Integer(
        help="The year, in the rule's own calendar, this occurrence was "
             "generated for.")
    generated = fields.Boolean(
        default=False,
        help="Computed from the calendar rather than observed. A generated "
             "date is replaced on the next run; a confirmed one never is.")
    suggested_date = fields.Date(
        readonly=True,
        help="A start date recovered from the sales themselves. Nothing moves "
             "until it is accepted.")
    suggestion_note = fields.Char(readonly=True)

    _date_order = models.Constraint(
        'CHECK (date_end >= date_start)',
        "An event cannot end before it starts.",
    )
    _one_per_rule_year = models.Constraint(
        'UNIQUE (rule_id, source_year)',
        "That occasion has already been generated for this year.",
    )

    def name_get(self):
        return [(e.id, '%s (%s)' % (e.name, e.date_start.strftime('%d %b %Y')))
                for e in self]

    # ------------------------------------------------------------------
    @api.model
    def _seed_shipped_calendar(self):
        """Run on install and on every upgrade, so a calendar added in a
        later version reaches databases that are already live. Only missing
        occasions are created; anything a user has edited is left alone.
        """
        seed_demand_events(self.env)

    @api.model
    def window(self, event):
        """First and last day the event influences, lead days included."""
        return (fields.Date.to_date(event['date_start'])
                - fields.Date.to_date(event['date_start']).resolution * 0,
                fields.Date.to_date(event['date_end']))

    # ------------------------------------------------------------------
    # recovering a real date from the sales themselves
    # ------------------------------------------------------------------
    @api.model
    def _daily_totals(self, first, last):
        """Total units sold per Bahrain trading day over a span."""
        self.env.flush_all()
        self.env.cr.execute("""
            SELECT (po.date_order + interval '3 hours')::date AS day,
                   SUM(pol.qty) AS qty
              FROM pos_order_line pol
              JOIN pos_order po ON po.id = pol.order_id
             WHERE po.state IN ('paid', 'done', 'invoiced')
               AND (po.date_order + interval '3 hours')::date
                   BETWEEN %(first)s AND %(last)s
             GROUP BY 1
        """, {'first': first, 'last': last})
        return {r['day']: float(r['qty'] or 0.0)
                for r in self.env.cr.dictfetchall()}

    def _detect_start(self):
        """The day in +/-SEARCH_RADIUS that carries this occasion's signature.

        Two signatures, both read off the real sales rather than assumed:

        * a closed occasion is the day the tills recorded **nothing** while the
          days around it traded normally - Ashura shows exactly this, four
          years running;
        * any other occasion is matched on *shape*: the run of daily totals
          across its window, divided by the ordinary level around it, compared
          against the same shape from the years already confirmed. The shift
          that fits best wins.

        Returns (date, note) or (None, reason).
        """
        self.ensure_one()
        span = (self.date_end - self.date_start).days + 1
        lead = self.lead_days or 0
        first = self.date_start - timedelta(days=SEARCH_RADIUS + lead + 28)
        last = self.date_end + timedelta(days=SEARCH_RADIUS + 28)
        totals = self._daily_totals(first, last)
        if not totals:
            return None, _("No sales recorded around this date.")

        if self.closed:
            return self._detect_closed_day(totals)

        profile = self._reference_profile(lead, span)
        if not profile:
            return None, _("No confirmed year of this occasion to compare with.")
        return self._best_shift(totals, profile, lead, span)

    def _detect_closed_day(self, totals):
        """A shut day: no tickets at all, with trading either side of it."""
        self.ensure_one()
        hits = []
        for shift in range(-SEARCH_RADIUS, SEARCH_RADIUS + 1):
            day = self.date_start + timedelta(days=shift)
            if totals.get(day, 0.0) > 0:
                continue
            before = totals.get(day - timedelta(days=1), 0.0)
            after = totals.get(day + timedelta(days=1), 0.0)
            if before > 0 and after > 0:
                hits.append(day)
        if len(hits) == 1:
            if hits[0] == self.date_start:
                return None, _("The date already lands on the closed day.")
            return hits[0], _("No sales at all on this day, trading either side.")
        if not hits:
            return None, _("No closed day found near this date.")
        return None, _("%s closed days near this date - too ambiguous to pick "
                       "one.", len(hits))

    def _reference_profile(self, lead, span):
        """Mean log-ratio shape of this occasion from the years already fixed."""
        self.ensure_one()
        peers = self.search([
            ('event_type', '=', self.event_type),
            ('confirmed', '=', True),
            ('id', '!=', self.id),
        ])
        offsets = list(range(-lead, span))
        stacks = {off: [] for off in offsets}
        for peer in peers:
            first = peer.date_start - timedelta(days=lead + 28)
            last = peer.date_start + timedelta(days=span + 28)
            totals = peer._daily_totals(first, last)
            ordinary = peer._ordinary_level(totals, peer.date_start, lead, span)
            if not ordinary:
                continue
            for off in offsets:
                qty = totals.get(peer.date_start + timedelta(days=off))
                if qty and qty > 0:
                    stacks[off].append(math.log(qty / ordinary))
        profile = {off: (sum(v) / len(v)) for off, v in stacks.items() if v}
        return profile if len(profile) >= 2 else {}

    @api.model
    def _ordinary_level(self, totals, start, lead, span):
        """Median daily total just outside the occasion - the 'normal' level."""
        inside = {start + timedelta(days=o) for o in range(-lead, span)}
        around = [q for d, q in totals.items()
                  if d not in inside and q > 0
                  and abs((d - start).days) <= 28 + lead + span]
        return median(around) if around else 0.0

    def _best_shift(self, totals, profile, lead, span):
        """Which +/- shift makes the real sales look most like the known shape."""
        self.ensure_one()
        best, best_score = None, None
        for shift in range(-SEARCH_RADIUS, SEARCH_RADIUS + 1):
            start = self.date_start + timedelta(days=shift)
            ordinary = self._ordinary_level(totals, start, lead, span)
            if not ordinary:
                continue
            score, seen = 0.0, 0
            for off, want in profile.items():
                qty = totals.get(start + timedelta(days=off))
                if not qty or qty <= 0:
                    continue
                score += (math.log(qty / ordinary) - want) ** 2
                seen += 1
            if seen < 2:
                continue
            score /= seen
            if best_score is None or score < best_score:
                best, best_score = start, score
        if best is None:
            return None, _("Not enough sales around this date to match a shape.")
        if best == self.date_start:
            return None, _("The computed date already fits the sales best.")
        return best, _("The sales pattern fits %(n)+d day(s) from the computed "
                       "date.", n=(best - self.date_start).days)

    def action_suggest_from_sales(self):
        """Fill in a suggestion. Writes no dates - that needs a second click."""
        found = 0
        for event in self:
            if event.date_start >= fields.Date.context_today(event):
                event.write({'suggested_date': False,
                             'suggestion_note': _("Still in the future - its "
                                                  "date has not happened yet.")})
                continue
            day, note = event._detect_start()
            event.write({'suggested_date': day, 'suggestion_note': note})
            found += bool(day)
        return {
            'type': 'ir.actions.client',
            'tag': 'display_notification',
            'params': {
                'type': 'success' if found else 'warning',
                'message': _("%(n)s date(s) recovered from the sales. Review "
                             "them, then accept.", n=found),
            },
        }

    def action_accept_suggestion(self):
        """Move the occasion onto the recovered date and mark it observed."""
        for event in self:
            if not event.suggested_date:
                raise UserError(_("There is no suggestion to accept on %s.",
                                  event.name))
            span = (event.date_end - event.date_start).days
            event.write({
                'date_start': event.suggested_date,
                'date_end': event.suggested_date + timedelta(days=span),
                'confirmed': True,
                'generated': False,     # observed now; the rule must not undo it
                'suggested_date': False,
                'suggestion_note': False,
            })


